-- ============================================================================
-- Unified Game Chat Migration
-- Upgrades public.game_chat_messages to support all games (Domino & Okey).
-- Incorporates accurate lifecycle checks (Active Membership) for read/write access.
-- ============================================================================

-- 1. Alter existing table to support multiple games
ALTER TABLE public.game_chat_messages RENAME COLUMN room_id TO match_id;
ALTER TABLE public.game_chat_messages ADD COLUMN IF NOT EXISTS game_type text NOT NULL DEFAULT 'domino';
ALTER TABLE public.game_chat_messages ALTER COLUMN mode DROP NOT NULL;

-- Find and drop the mode constraint dynamically since its name might be autogenerated
DO $$
DECLARE
  v_constraint_name text;
BEGIN
  SELECT conname INTO v_constraint_name
  FROM pg_constraint
  WHERE conrelid = 'public.game_chat_messages'::regclass
    AND contype = 'c'
    AND pg_get_expr(conbin, conrelid) ILIKE '%mode%';
    
  IF v_constraint_name IS NOT NULL THEN
    EXECUTE 'ALTER TABLE public.game_chat_messages DROP CONSTRAINT ' || v_constraint_name;
  END IF;
END $$;

-- 2. Indexes
DROP INDEX IF EXISTS public.idx_game_chat_messages_room_mode_created;
CREATE INDEX IF NOT EXISTS idx_game_chat_messages_unified 
ON public.game_chat_messages(game_type, match_id, created_at);

-- 3. Safely manage RLS dependencies FIRST
DROP POLICY IF EXISTS "game_chat_messages_select_room_members" ON public.game_chat_messages;

-- 4. Replace old functions with new Unified versions
-- Now it's safe to drop because the dependent policy is gone
DROP FUNCTION IF EXISTS public.is_game_room_member(text, uuid, uuid);
DROP FUNCTION IF EXISTS public.send_game_chat_message(text, uuid, text);

CREATE OR REPLACE FUNCTION public.is_game_room_member(
  p_game_type text,
  p_match_id uuid,
  p_user_id uuid DEFAULT auth.uid(),
  p_mode text DEFAULT NULL
)
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = public, okey, pg_temp
AS $$
  SELECT CASE
    WHEN p_user_id IS NULL THEN false
    
    -- Domino: Check players table and ensure they haven't permanently left
    WHEN p_game_type = 'domino' AND p_mode = '1v1' THEN EXISTS (
      SELECT 1
      FROM public.one_vs_one_players
      WHERE room_id = p_match_id
        AND user_id = p_user_id
        AND left_at IS NULL
    )
    WHEN p_game_type = 'domino' AND p_mode = '2v2' THEN EXISTS (
      SELECT 1
      FROM public.two_vs_two_players
      WHERE room_id = p_match_id
        AND user_id = p_user_id
        AND left_at IS NULL
    )
    
    -- Okey: Check match_seats and ensure membership is not released (bot takeover/manual leave)
    WHEN p_game_type = 'okey' THEN EXISTS (
      SELECT 1
      FROM okey.match_seats
      WHERE match_id = p_match_id
        AND user_id = p_user_id
        AND membership_released_at IS NULL
    )
    
    ELSE false
  END;
$$;

CREATE OR REPLACE FUNCTION public.send_game_chat_message(
  p_game_type text,
  p_match_id uuid,
  p_body text,
  p_mode text DEFAULT NULL
)
RETURNS public.game_chat_messages
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_user_id uuid := auth.uid();
  v_body text := btrim(COALESCE(p_body, ''));
  v_profile public.profiles%ROWTYPE;
  v_message public.game_chat_messages%ROWTYPE;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  IF p_match_id IS NULL THEN
    RAISE EXCEPTION 'match_id is required';
  END IF;

  IF char_length(v_body) = 0 THEN
    RAISE EXCEPTION 'Message is required';
  END IF;

  IF char_length(v_body) > 500 THEN
    RAISE EXCEPTION 'Message is too long';
  END IF;

  IF NOT public.is_game_room_member(p_game_type, p_match_id, v_user_id, p_mode) THEN
    RAISE EXCEPTION 'You are not a member of this match';
  END IF;

  SELECT *
  INTO v_profile
  FROM public.profiles
  WHERE id = v_user_id;

  INSERT INTO public.game_chat_messages (
    game_type,
    mode,
    match_id,
    sender_user_id,
    sender_name,
    sender_avatar_id,
    body
  ) VALUES (
    p_game_type,
    p_mode,
    p_match_id,
    v_user_id,
    COALESCE(NULLIF(v_profile.username, ''), 'Player'),
    v_profile.avatar_id,
    v_body
  )
  RETURNING * INTO v_message;

  RETURN v_message;
END;
$$;

GRANT EXECUTE ON FUNCTION public.is_game_room_member(text, uuid, uuid, text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.send_game_chat_message(text, uuid, text, text) TO authenticated;

-- 5. Recreate RLS Policy with new function signature
CREATE POLICY "game_chat_messages_select_room_members"
ON public.game_chat_messages
FOR SELECT
TO authenticated
USING (public.is_game_room_member(game_type, match_id, auth.uid(), mode));

-- 6. Drop old Okey chat components securely
DROP FUNCTION IF EXISTS public.okey_post_chat_message(uuid, uuid, text);
DROP TABLE IF EXISTS okey.match_chat_messages;
